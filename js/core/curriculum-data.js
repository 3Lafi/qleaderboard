export function curriculumSystems(countryId) {
    return CURRICULUM_SYSTEMS.filter(s => s.countryId === countryId);
}

export function curriculumStages(countryId, systemId) {
    return CURRICULUM_STAGES.filter(s => s.countryId === countryId && s.systemId === systemId);
}

export function curriculumLevels(countryId, systemId, stageId) {
    return CURRICULUM_LEVELS
        .filter(l => l.countryId === countryId && l.systemId === systemId && l.stageId === stageId)
        .sort((a, b) => a.levelNum - b.levelNum);
}

export function curriculumTerms(countryId) {
    return CURRICULUM_TERMS.filter(t => t.countryId === countryId);
}

// termId = null يعني السنة الدراسية كاملة (اتحاد سور كل الفصول لهذا الصف)
export function resolveCurriculumSurahs({ countryId, systemId, stageId, levelId, termId }) {
    const set = new Set();
    for (const [c, sy, st, l, t, surahs] of CURRICULUM_ASSIGNMENTS) {
        if (c === countryId && sy === systemId && st === stageId && l === levelId && (termId == null || t === termId)) {
            surahs.forEach(n => set.add(n));
        }
    }
    return [...set].sort((a, b) => a - b);
}
